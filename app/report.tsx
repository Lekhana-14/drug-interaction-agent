import { Text, View, Pressable, ScrollView, Alert } from "react-native";
import { useRouter } from "expo-router";
import * as Sharing from "expo-sharing";
import * as FileSystem from "expo-file-system/legacy";
import { Platform } from "react-native";
import * as Haptics from "expo-haptics";
import { LinearGradient } from "expo-linear-gradient";

import { ScreenContainer } from "@/components/screen-container";
import { IconSymbol } from "@/components/ui/icon-symbol";
import { useMedications } from "@/lib/medicationStore";
import { checkAllInteractions } from "@/lib/drugDatabase";
import { useColors } from "@/hooks/use-colors";

function triggerHaptic() {
  if (Platform.OS !== "web") {
    Haptics.impactAsync(Haptics.ImpactFeedbackStyle.Light);
  }
}

const SEVERITY_CONFIG = {
  severe: { gradient: ["#DC2626", "#F87171"], bg: "#FEF2F2", text: "#DC2626" },
  moderate: { gradient: ["#EA580C", "#FB923C"], bg: "#FFF7ED", text: "#EA580C" },
  mild: { gradient: ["#CA8A04", "#FACC15"], bg: "#FEFCE8", text: "#CA8A04" },
};

export default function ReportScreen() {
  const router = useRouter();
  const { medicines } = useMedications();
  const colors = useColors();

  const interactions = medicines.length >= 2
    ? checkAllInteractions(medicines)
    : [];

  const severeCount = interactions.filter((i) => i.severity === "severe").length;
  const moderateCount = interactions.filter((i) => i.severity === "moderate").length;
  const mildCount = interactions.filter((i) => i.severity === "mild").length;
  const totalIssues = severeCount + moderateCount + mildCount;

  const formatDate = (isoString: string) => {
    const date = new Date(isoString);
    return date.toLocaleDateString("en-US", {
      month: "short",
      day: "numeric",
      year: "numeric",
    });
  };

  const handleShareReport = async () => {
    triggerHaptic();

    let report = "MEDCHECK — Drug Interaction Report\n";
    report += "=".repeat(40) + "\n";
    report += `Generated: ${new Date().toLocaleString()}\n\n`;

    report += "CURRENT MEDICATIONS:\n";
    report += "-".repeat(30) + "\n";
    medicines.forEach((med) => {
      report += `  ${med.name} (${med.dosage}) — ${med.doctor}\n`;
    });

    if (interactions.length > 0) {
      report += "\nFLAGGED INTERACTIONS:\n";
      report += "-".repeat(30) + "\n";
      report += `Severe: ${severeCount} | Moderate: ${moderateCount} | Mild: ${mildCount}\n\n`;
      interactions.forEach((interaction) => {
        report += `[${interaction.severity.toUpperCase()}] ${interaction.drug1} + ${interaction.drug2}\n`;
        report += `  ${interaction.description}\n`;
        report += `  Recommendation: ${interaction.recommendation}\n\n`;
      });
    } else {
      report += "\nNo drug interactions detected.\n";
    }

    report += "\n" + "=".repeat(40) + "\n";
    report += "Generated by MedCheck — Drug Interaction Checker\n";
    report += "This report is for informational purposes only.\n";
    report += "Consult your doctor before making any medication changes.\n";

    if (Platform.OS === "web") {
      try {
        await navigator.clipboard.writeText(report);
        Alert.alert("Report Copied", "Report has been copied to clipboard!");
      } catch {
        Alert.alert("Report", report);
      }
    } else {
      try {
        const fileUri = FileSystem.documentDirectory + "MedCheck_Report.txt";
        await FileSystem.writeAsStringAsync(fileUri, report);
        if (await Sharing.isAvailableAsync()) {
          await Sharing.shareAsync(fileUri, {
            mimeType: "text/plain",
            dialogTitle: "Share Drug Interaction Report",
          });
        }
      } catch (e) {
        console.error("Share failed:", e);
        Alert.alert("Share Failed", "Could not generate report file.");
      }
    }
  };

  return (
    <ScreenContainer className="px-5 pt-6">
      <ScrollView showsVerticalScrollIndicator={false}>
        <View className="gap-5">
          {/* Header */}
          <View className="flex-row items-center gap-3 mb-2">
            <Pressable onPress={() => router.back()} style={{ opacity: 0.9 }}>
              <IconSymbol name="chevron.left.forwardslash.chevron.right" size={24} color={colors.primary} />
            </Pressable>
            <View className="flex-1">
              <Text className="text-xl font-bold text-foreground">
                Report
              </Text>
              <Text className="text-muted text-sm">
                Share with your doctor
              </Text>
            </View>
          </View>

          {/* Report Header Card */}
          <LinearGradient
            colors={["#0EA5E9", "#6366F1"]}
            start={{ x: 0, y: 0 }}
            end={{ x: 1, y: 1 }}
            className="rounded-2xl p-5"
            style={{ elevation: 4 }}
          >
            <View className="flex-row items-center gap-3 mb-3">
              <View className="bg-white/20 rounded-xl p-2.5">
                <IconSymbol name="doc.text.fill" size={26} color="#FFFFFF" />
              </View>
              <View className="flex-1">
                <Text className="text-white font-bold text-lg">
                  Drug Interaction Report
                </Text>
                <Text className="text-white/80 text-xs mt-0.5">
                  Generated on {new Date().toLocaleDateString()}
                </Text>
              </View>
            </View>
            <View className="flex-row gap-4">
              <View className="bg-white/15 rounded-lg px-3 py-1.5">
                <Text className="text-white/90 text-xs font-semibold">
                  {medicines.length} Medications
                </Text>
              </View>
              <View className="bg-white/15 rounded-lg px-3 py-1.5">
                <Text className="text-white/90 text-xs font-semibold">
                  {interactions.length} Flags
                </Text>
              </View>
            </View>
          </LinearGradient>

          {/* Medications List */}
          <View>
            <Text className="text-foreground font-bold mb-3">
              Current Medications ({medicines.length})
            </Text>
            {medicines.map((med) => (
              <View key={med.id} className="bg-surface rounded-2xl p-4 border border-border mb-2 shadow-sm">
                <View className="flex-row justify-between items-center">
                  <View className="flex-1">
                    <Text className="text-foreground font-bold text-sm">
                      {med.name}
                    </Text>
                    <Text className="text-muted text-xs mt-0.5">
                      {med.dosage} · {med.doctor}
                    </Text>
                    <Text className="text-muted text-xs">
                      Added: {formatDate(med.addedDate)}
                    </Text>
                  </View>
                  <View className="bg-primary/10 rounded-xl px-3 py-1.5">
                    <Text className="text-primary text-xs font-semibold">
                      {med.category}
                    </Text>
                  </View>
                </View>
              </View>
            ))}
          </View>

          {/* Interactions Section */}
          <View>
            <Text className="text-foreground font-bold mb-3">
              Flagged Interactions ({interactions.length})
            </Text>

            {interactions.length === 0 ? (
              <LinearGradient
                colors={["#10B981", "#34D399"]}
                start={{ x: 0, y: 0 }}
                end={{ x: 1, y: 1 }}
                className="rounded-2xl p-5 items-center"
                style={{ elevation: 4 }}
              >
                <IconSymbol name="checkmark.seal.fill" size={36} color="#FFFFFF" />
                <Text className="text-white font-bold mt-2">
                  No Interactions Detected
                </Text>
                <Text className="text-white/80 text-sm text-center mt-1">
                  Your medications appear safe to take together
                </Text>
              </LinearGradient>
            ) : (
              <View className="gap-3">
                {/* Summary */}
                <View className="flex-row gap-3">
                  {severeCount > 0 && (
                    <LinearGradient
                      colors={SEVERITY_CONFIG.severe.gradient as [string, string]}
                      start={{ x: 0, y: 0 }}
                      end={{ x: 1, y: 1 }}
                      className="flex-1 rounded-xl p-3 items-center"
                    >
                      <Text className="text-white text-lg font-bold">{severeCount}</Text>
                      <Text className="text-white/80 text-xs">Severe</Text>
                    </LinearGradient>
                  )}
                  {moderateCount > 0 && (
                    <LinearGradient
                      colors={SEVERITY_CONFIG.moderate.gradient as [string, string]}
                      start={{ x: 0, y: 0 }}
                      end={{ x: 1, y: 1 }}
                      className="flex-1 rounded-xl p-3 items-center"
                    >
                      <Text className="text-white text-lg font-bold">{moderateCount}</Text>
                      <Text className="text-white/80 text-xs">Moderate</Text>
                    </LinearGradient>
                  )}
                  {mildCount > 0 && (
                    <LinearGradient
                      colors={SEVERITY_CONFIG.mild.gradient as [string, string]}
                      start={{ x: 0, y: 0 }}
                      end={{ x: 1, y: 1 }}
                      className="flex-1 rounded-xl p-3 items-center"
                    >
                      <Text className="text-white text-lg font-bold">{mildCount}</Text>
                      <Text className="text-white/80 text-xs">Mild</Text>
                    </LinearGradient>
                  )}
                </View>

                {/* Interaction Details */}
                {interactions.map((interaction, index) => {
                  const config = SEVERITY_CONFIG[interaction.severity];
                  return (
                    <View key={index} style={{ borderRadius: 16, overflow: "hidden", borderWidth: 0.5, borderColor: colors.border }}>
                      <LinearGradient
                        colors={config.gradient as [string, string]}
                        start={{ x: 0, y: 0 }}
                        end={{ x: 1, y: 0 }}
                        style={{ height: 3 }}
                      />
                      <View style={{ backgroundColor: colors.surface, padding: 14 }}>
                        <View className="flex-row items-center gap-6 mb-2">
                          <Text className="text-foreground font-bold text-sm flex-1">
                            {interaction.drug1}
                          </Text>
                          <View style={{ backgroundColor: config.bg, paddingHorizontal: 6, paddingVertical: 2, borderRadius: 6 }}>
                            <Text style={{ color: config.text, fontSize: 10, fontWeight: "700" }}>+</Text>
                          </View>
                          <Text className="text-foreground font-bold text-sm flex-1 text-right">
                            {interaction.drug2}
                          </Text>
                        </View>
                        <LinearGradient
                          colors={config.gradient as [string, string]}
                          start={{ x: 0, y: 0 }}
                          end={{ x: 1, y: 0 }}
                          className="rounded-full px-3 py-0.5 self-start mb-2"
                        >
                          <Text style={{ color: "#FFFFFF", fontSize: 10, fontWeight: "700" }}>
                            {interaction.severity.toUpperCase()}
                          </Text>
                        </LinearGradient>
                        <Text className="text-muted text-xs mb-2">
                          {interaction.mechanism}
                        </Text>
                        <View style={{ backgroundColor: config.bg, padding: 10, borderRadius: 10, borderLeftWidth: 3, borderLeftColor: config.text }}>
                          <Text style={{ color: config.text, fontSize: 12, fontWeight: "500", lineHeight: 18 }}>
                            {interaction.recommendation}
                          </Text>
                        </View>
                      </View>
                    </View>
                  );
                })}
              </View>
            )}
          </View>

          {/* Disclaimer */}
          <View className="bg-surface rounded-2xl p-4 border border-border">
            <View className="flex-row items-start gap-3">
              <View className="bg-warning/10 rounded-lg p-1.5 mt-0.5">
                <IconSymbol name="exclamationmark.triangle.fill" size={16} color={colors.warning} />
              </View>
              <Text className="text-muted text-xs flex-1 leading-relaxed">
                This report is generated for informational purposes only and should not replace professional medical advice.
                Always consult your doctor or pharmacist before making any changes to your medication regimen.
                MedCheck uses a curated subset of common, well-documented medicine interactions.
              </Text>
            </View>
          </View>

          {/* Share Button */}
          <Pressable
            onPress={handleShareReport}
            style={({ pressed }) => ({
              transform: [{ scale: pressed ? 0.97 : 1 }],
              opacity: pressed ? 0.9 : 1,
            })}
          >
            <LinearGradient
              colors={["#0EA5E9", "#6366F1"]}
              start={{ x: 0, y: 0 }}
              end={{ x: 1, y: 1 }}
              className="rounded-2xl p-4 flex-row items-center justify-center gap-3"
              style={{ elevation: 4 }}
            >
              <IconSymbol name="square.and.arrow.up" size={22} color="#FFFFFF" />
              <Text className="text-white font-bold text-base">
                Share Report
              </Text>
            </LinearGradient>
          </Pressable>
        </View>
      </ScrollView>
    </ScreenContainer>
  );
}
